#!/usr/bin/env python3
"""Generate stage1/power-overlay.dtso: CPU OPP tables whose opp-peak-kBps follows the stock memlat cpufreq->DDR tables
(stock-dt/dtb2.dts qcom,memlat ddr group: silver/gold/prime), plus the simpledrm display bandwidth vote.
CPU frequencies = cpufreq-hw LUT (scaling_available_frequencies on the tablet). DDR path bandwidth = DDR kHz * 4 (EBI width)."""
import sys

LUT = {  # policy: (cpus, kHz list)
    'silver': ([0, 1, 2], [364800, 441600, 595200, 787200, 902400, 1017600, 1113600, 1228800, 1344000, 1478400,
                          1593600, 1708800, 1843200, 1900800]),
    'gold': ([3, 4, 5, 6], [480000, 633600, 787200, 940800, 1056000, 1190400, 1286400, 1401600, 1497600, 1593600,
                            1708800, 1824000, 1920000, 2073600, 2188800, 2361600, 2572800, 2611200]),
    'prime': ([7], [480000, 633600, 787200, 960000, 1094400, 1209600, 1324800, 1459200, 1651200, 1766400, 1900800,
                    2150400, 2304000, 2457600, 2668800, 2803200]),
}
MEMLAT = {  # stock qcom,cpufreq-memfreq-tbl: (cpu kHz upper bound, DDR kHz)
    'silver': [(1113600, 547000), (1478400, 768000), (1843200, 1555000)],
    'gold': [(633600, 547000), (1190400, 1555000), (1401600, 1708000), (1824000, 2736000), (2572800, 3686400),
             (2611200, 4224000)],
    'prime': [(633600, 547000), (960000, 768000), (1209600, 1555000), (1459200, 1708000), (2150400, 2736000),
              (2668800, 3686400), (2803200, 4224000)],
}
DISPLAY_KBPS = 3000000  # 1600x2560 RGBA @ 144 Hz = 2.36 GB/s scanout, plus margin


def ddr(cluster, khz):
    for bound, mem in MEMLAT[cluster]:
        if khz <= bound:
            return mem
    return MEMLAT[cluster][-1][1]


out = ['// SPDX-License-Identifier: GPL-2.0-only', '/* Generated by scripts/gen-power-overlay.py - edit the script. */',
       '/dts-v1/;', '/plugin/;', '',
       '&mmss_noc {', '\tstatus = "okay";', '};', '',
       '&{/framebuffer@e3940000} {',
       '\tinterconnects = <&mmss_noc 21 &mc_virt 512>;  /* MASTER_MDP -> SLAVE_EBI1 */',
       '\tinterconnect-names = "mdp0-mem";', f'\tu880,icc-peak-kBps = <{DISPLAY_KBPS}>;', '};', '',
       '&{/} {']
for cl, (cpus, freqs) in LUT.items():
    out += [f'\tu880_{cl}_opp: opp-table-u880-{cl} {{', '\t\tcompatible = "operating-points-v2";', '\t\topp-shared;']
    for f in freqs:
        out += [f'\t\topp-{f * 1000} {{', f'\t\t\topp-hz = /bits/ 64 <{f * 1000}>;',
                f'\t\t\topp-peak-kBps = <{ddr(cl, f) * 4}>;', '\t\t};']
    out += ['\t};']
out += ['};', '']
for cl, (cpus, _) in LUT.items():
    for c in cpus:
        out += [f'&{{/cpus/cpu@{c * 100 if c else 0}}} {{',  # unit addresses 0, 100, ... 700 (MPIDR)
                f'\toperating-points-v2 = <&u880_{cl}_opp>;',
                '\tinterconnects = <&gem_noc 2 &mc_virt 512>;  /* MASTER_APPSS_PROC -> SLAVE_EBI1 */', '};', '']
sys.stdout.write('\n'.join(out))
